export type TranslationConfidence = "high" | "medium" | "low" | "unknown";

export type TranslationHit = {
  english: string | null;
  confidence: TranslationConfidence;
  notes: string[];
};

export function lookupTranslation(category: keyof typeof translationDictionary, value: unknown): TranslationHit {
  return lookupByTable(translationDictionary[category], value);
}

function lookupByTable(
  table: Record<string, { english: string; confidence: TranslationConfidence; notes: string[] }>,
  value: unknown
): TranslationHit {
  if (typeof value !== "string") {
    return { english: null, confidence: "unknown", notes: [] };
  }

  const trimmed = value.trim();
  if (!trimmed) {
    return { english: null, confidence: "unknown", notes: [] };
  }

  const entry = table[trimmed];
  if (!entry) {
    return { english: null, confidence: "unknown", notes: [] };
  }

  return { english: entry.english, confidence: entry.confidence, notes: [...entry.notes] };
}

export function translatePartialEffectText(value: unknown): { text: string | null; notes: string[] } {
  if (typeof value !== "string") return { text: null, notes: [] };
  const trimmed = value.trim();
  if (!trimmed) return { text: null, notes: [] };

  let translated = trimmed;
  let applied = false;
  for (const [source, target] of [...partialEffectTerms].sort((a, b) => b[0].length - a[0].length)) {
    if (translated.includes(source)) {
      translated = translated.split(source).join(target);
      applied = true;
    }
  }

  if (!applied) {
    return { text: null, notes: [] };
  }

  return { text: translated, notes: ["Full effect translation pending manual verification."] };
}
